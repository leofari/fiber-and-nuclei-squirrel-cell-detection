def run_final_from_local_zips(
    quantified_zip=None,
    unquantified_zip=None,
    quantified_dir="data/quantified",
    unquantified_dir="data/unquantified",
    exts=(".jpg",".jpeg",".png",".tif",".tiff"),
    n=None # number of image pairs to process (takes around 40 seconds per pair)
    # full data set would take like an hour and a half
):
    # check zips exist
    if not os.path.exists(quantified_zip):
        raise FileNotFoundError(f"Missing quantified zip: {quantified_zip}")
    if not os.path.exists(unquantified_zip):
        raise FileNotFoundError(f"Missing unquantified zip: {unquantified_zip}")

    print("Found zip files.")

    # Reset folders
    wipe_dir(quantified_dir)
    wipe_dir(unquantified_dir)

    # Unzip
    unzip_to(quantified_zip, quantified_dir)
    unzip_to(unquantified_zip, unquantified_dir)

    # Collect images
    q_paths = collect_image_paths(quantified_dir, exts)
    r_paths = collect_image_paths(unquantified_dir, exts)

    print("Extracted image counts:")
    print("  quantified:", len(q_paths))
    print("  unquantified:", len(r_paths))

    # Build maps
    q_map, q_dupes = build_basename_map(q_paths)
    r_map, r_dupes = build_basename_map(r_paths)

    if q_dupes:
        print("Duplicate quantified filenames:", q_dupes[:10])
    if r_dupes:
        print("Duplicate unquantified filenames:", r_dupes[:10])

    # Process
    all_dfs = []
    unmatched = []
    errors = []

    processed_pairs = 0

    out_dir = "outputs"
    os.makedirs(out_dir, exist_ok=True)


    for qname in q_map:
        raw_name = find_raw_for_quantified(qname, list(r_map.keys()))
        if raw_name is None or raw_name not in r_map:
            unmatched.append(qname)
            print(f"No raw match for quantified: {qname}")
            continue

        if n is not None and processed_pairs >= n:
            break

        annotated_path = q_map[qname]
        unannotated_path = r_map[raw_name]

        print(f"\nProcessing pair:\n  Raw: {raw_name}\n  Annotated: {qname}")

        try:
            matched_fibers = get_matched_fibers(annotated_path, unannotated_path)

            annotated_vis = draw_fibers_and_nuclei_annotated(
                unannotated_path,
                matched_fibers,
                use_existing_index=True
            )

            base = os.path.splitext(os.path.basename(unannotated_path))[0]
            out_path = os.path.join(out_dir, f"annotated_{base}.png")

            cv2.imwrite(
                out_path,
                cv2.cvtColor(annotated_vis, cv2.COLOR_RGB2BGR)
            )

            df = fiber_metrics_dataframe(unannotated_path, matched_fibers, True)
            df["source_image"] = raw_name
            df["quantified_image"] = qname
            all_dfs.append(df)

            processed_pairs += 1

        
        except Exception as e:
            errors.append((raw_name, qname, str(e)))
            print(f"Error processing raw={raw_name}: {e}")

    if not all_dfs:
        raise RuntimeError("No objects to concatenate.")

    final_df = pd.concat(all_dfs, ignore_index=True)

    print("\nDone.")
    print("  processed pairs:", len(all_dfs))
    print("  unmatched quantified:", len(unmatched))
    print("  errors:", len(errors))

    return final_df, unmatched, errors

