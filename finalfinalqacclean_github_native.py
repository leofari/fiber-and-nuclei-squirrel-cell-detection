"""### Draw Bounding Circles Around Nuclei
Given an image path, it returns:
- An RGB image with circles around nuclei
- A list of nuclei centers
- A list of nucleus radii  

The function:
- Builds a nuclei mask with build_second_mask
- Finds the contours of the nuclei
- Filters out nuclei which are too small
- Appends the coordinates and radius size of each nuclei to seperate lists

"""

def bounding_boxes_nuc(impath):
    #takes an image path, returns:
    # - an RGB image with circles around nuclei
    # - a list of nucleus centers
    # - a list of nucleus radii

    nuc_mask_sep = build_second_mask(impath)

    contours, _ = cv2.findContours(  # finds contours of nuclei
        nuc_mask_sep, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE
    )

    areas = np.array([cv2.boundingRect(c)[2] * cv2.boundingRect(c)[3] for c in contours])
    median_area = np.median(areas)
    min_area = 0.35 * median_area  # disregard nuclei that are too small (likely just noise)

    img = cv2.imread(impath, 1)

    nuc_centers = []
    nuc_radii = []

    for c in contours:
        x, y, w, h = cv2.boundingRect(c)
        area = w * h
        if area > min_area:
            cx = x + w // 2
            cy = y + h // 2
            r = int(0.6 * max(w, h))  # circle radius based on nucleus size

            nuc_centers.append((cx, cy))
            nuc_radii.append(r)

            # draw detection circle
            cv2.circle(img, (cx, cy), r, (0, 0, 255), 2)

    img_rgb = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
    return img_rgb, nuc_centers, nuc_radii

