"""### Find matched fibers on unannotated image"""

def find_fiber_candidates_matched(path, gt_training_fibers):
    """
    Detect fibers on the unannotated image using get_fiber_candidates(),
    then match each GT fiber to the nearest unused detected fiber
    by centroid distance.

    Returns a list of dicts with keys:
    contour, centroid, area, index, nuclei_count
    """

    # nuclei detection once
    _, nuc_centers, nuc_radii = bounding_boxes_nuc(path)

    # detect fibers
    auto_fibers = get_fiber_candidates(path)


    base_img = cv2.imread(path, cv2.IMREAD_COLOR)
    h, w = base_img.shape[:2]

    dilate_kernel_size = (20, 20)
    dilate_iters = 2
    dist_limit = 40

    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, dilate_kernel_size)

    used = set()
    matched = []

    for gt in gt_training_fibers:
        gx, gy = gt["centroid"]
        gt_index = gt.get("index", None)

        # find nearest unused auto fiber
        best_j = None
        best_d = float("inf")

        for j, af in enumerate(auto_fibers):
            if j in used:
                continue
            ax, ay = af["centroid"]
            d = (ax - gx) ** 2 + (ay - gy) ** 2
            if d < best_d:
                best_d = d
                best_j = j

        if best_j is None:
            continue

        used.add(best_j)
        af = auto_fibers[best_j]
        cnt = af["contour"]

        # build expanded contour
        temp = np.zeros((h, w), dtype=np.uint8)
        cv2.drawContours(temp, [cnt], -1, 255, 1)
        temp = cv2.dilate(temp, kernel, iterations=dilate_iters)

        new_cnts, _ = cv2.findContours(temp, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
        exp_cnt = new_cnts[0] if new_cnts else cnt

        # count nuclei attached to this fiber
        myon = 0
        for (nx, ny), r in zip(nuc_centers, nuc_radii):
            d = cv2.pointPolygonTest(exp_cnt, (float(nx), float(ny)), True)
            if d >= -dist_limit:
                myon += 1

        matched.append({
            "contour": cnt,
            "centroid": af["centroid"],
            "area": af.get("area", cv2.contourArea(cnt)),
            "index": gt_index,
            "nuclei_count": myon
        })

    return matched

