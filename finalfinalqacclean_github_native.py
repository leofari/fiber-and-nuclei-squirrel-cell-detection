def find_pixel_to_nano(path):
  #given an image path, it returns a scalar k st pixel*k = nano meters
  img = cv2.imread(path, cv2.IMREAD_GRAYSCALE)
  _, white_image = cv2.threshold(img, 230, 255, cv2.THRESH_BINARY)

  contours, _ = cv2.findContours(white_image, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)


  # k = nano/pixel

  h, w = white_image.shape
  min_x = w
  max_x = 0
  for contour in contours:
    for point in contour:
      x, y = point[0]
      if x < min_x:
        min_x = x
      if x > max_x:
        max_x = x

  return(100/(max_x-min_x))

def invert_nanometer_legend(img):
    #Invert ONLY the pure-white pixels (the scale bar + text) in the image.

    legend_mask = cv2.inRange(img, (220, 220, 220),(255, 255, 255))

    img[legend_mask > 0] = (0, 0, 0)

    return img

