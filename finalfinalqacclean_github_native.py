"""## Computing Fiber Metrics"""

def compute_fiber_metrics(path, fibers, use_existing_index=False):
    """
    Given:
      - path: image path
      - fibers: list of fiber dicts produced by get_fiber_candidates()
      - use_existing_index: if True and fiber["index"] exists, use that
        as Fiber ID instead of 1 to N

    Returns a list of dicts, one per fiber, with keys:
      - fiber_id
      - centroid
      - area_px
      - CSA
      - nuclei_count
      - nuclei_indices (indices into the global nuclei list)
      - contour (original, non-expanded contour)
    """

    dilate_kernel_size = (20, 20)
    dilate_iters = 2
    dist_limit = 40  # how far in px from expanded contour a nucleus can be

    #load dimensions of image (for mask)
    base_img = cv2.imread(path, cv2.IMREAD_COLOR)
    h, w = base_img.shape[:2]

    #nuclei detection
    _, nuc_centers, nuc_radii = bounding_boxes_nuc(path)

    #kernel for expanding contours
    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, dilate_kernel_size)

    #area conversions for CSA
    px_to_unit = find_pixel_to_nano(path)
    area_scale = px_to_unit ** 2

    fiber_metrics = []

    for idx, f in enumerate(fibers, start=1):
        cnt = f["contour"]
        cx, cy = f["centroid"]
        area_px = f.get("area", cv2.contourArea(cnt))

        #fiber_id is either preassigned (if for training) or just 1 to N
        if use_existing_index and ("index" in f) and (f["index"] is not None):
            fiber_id = int(f["index"])
        else:
            fiber_id = idx

        # build expanded contour mask (to find attached nuclei)
        temp = np.zeros((h, w), dtype=np.uint8)
        cv2.drawContours(temp, [cnt], -1, 255, 1)
        temp = cv2.dilate(temp, kernel, iterations=dilate_iters)

        new_cnts, _ = cv2.findContours(temp, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
        exp_cnt = new_cnts[0] if new_cnts else cnt

        # assign nuclei to this fiber using distance to expanded contour
        nuclei_indices = []
        for n_idx, ((nx, ny), r) in enumerate(zip(nuc_centers, nuc_radii)):
            d = cv2.pointPolygonTest(exp_cnt, (float(nx), float(ny)), True)
            if d >= -dist_limit:
                nuclei_indices.append(n_idx)

        csa = area_px * area_scale

        fiber_metrics.append({
            "fiber_id": fiber_id,
            "centroid": (cx, cy),
            "area_px": area_px,
            "CSA": csa,
            "nuclei_count": len(nuclei_indices),
            "nuclei_indices": nuclei_indices,
            "contour": cnt
        })

    return fiber_metrics

