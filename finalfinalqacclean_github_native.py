"""### Building Second Nuclei Mask
Build second mask by:
- Run the first mask function
- Use morphology to fill holes and remove noise
- Find the contours to determine the average area of a nuclei
- Erode nuclei based on the average area calculated (larger area, more erosion)

Returns a cv2 image of the second mask
"""

def build_second_mask(impath):

  #Given an image path, return a cleaned and partially separated nuclei mask.

  nuc_mask = build_first_mask(impath)
  kernel = np.ones((2, 2), np.uint8)

  # use morphology to fill holes and remove noise
  nuc_mask_clean = cv2.morphologyEx(nuc_mask, cv2.MORPH_OPEN, kernel, iterations=1)
  nuc_mask_clean = cv2.morphologyEx(nuc_mask_clean, cv2.MORPH_CLOSE, kernel, iterations=1)

  # estimate nucleus size without heavy erosion
  contours0, _ = cv2.findContours(
      nuc_mask_clean, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE
  )

  areas0 = np.array([cv2.boundingRect(c)[2] * cv2.boundingRect(c)[3] for c in contours0])
  median_area = np.median(areas0)

  radius_px = (median_area ** 0.5) / 2.0 # treat bbox as ~diameter^2

  # pick erosion iterations based on radius: small for small nuclei, a bit bigger for big ones
  erode_iters = int(max(1, min(3, round(radius_px / 5))))  # between 1 and 3

  # now do the separation erosion with adaptive iters
  nuc_mask_sep = cv2.erode(nuc_mask_clean, kernel, iterations=erode_iters)

  return nuc_mask_sep

