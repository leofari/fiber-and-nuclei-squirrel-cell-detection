"""####OCR on Mask for indexes"""

def ocr_single_digit(idx_mask, centroid, radius=60):
    cx, cy = int(centroid[0]), int(centroid[1])
    H, W = idx_mask.shape

    # crop circular ROI
    x1, y1 = max(0, cx - radius), max(0, cy - radius)
    x2, y2 = min(W, cx + radius), min(H, cy + radius)

    roi = idx_mask[y1:y2, x1:x2]

    # upscale for OCR
    up = cv2.resize(roi, None, fx=4, fy=4, interpolation=cv2.INTER_LINEAR)

    # threshold
    _, bw = cv2.threshold(up, 0, 255, cv2.THRESH_BINARY + cv2.THRESH_OTSU)

    # invert if needed
    if np.mean(bw) < 127:
        bw = 255 - bw

    # OCR config
    config = "--psm 10 -c tessedit_char_whitelist=0123456789"
    text = pytesseract.image_to_string(bw, config=config).strip()

    return int(text) if text.isdigit() else None

