def draw_fibers_and_nuclei_annotated(
    path,
    fibers=None,
    use_existing_index=False
):
    """
    Given an image path, draw:

      - expanded fiber outlines in yellow
      - fiber IDs at centroids
      - attached nuclei as yellow circles with per-fiber nucleus IDs

    Returns:
      annotated RGB image (numpy array).
    """
    dilate_kernel_size=(20, 20)
    dilate_iters=2
    dist_limit=40

    base_bgr = cv2.imread(path)
    base_img = cv2.cvtColor(base_bgr, cv2.COLOR_BGR2RGB)
    annotated = base_img.copy()

    # use same nuclei + kernel settings as compute_fiber_metrics
    _, nuc_centers, nuc_radii = bounding_boxes_nuc(path)
    h, w = annotated.shape[:2]
    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, dilate_kernel_size)

    if fibers is None:
        fibers = get_fiber_candidates(path)

    font = cv2.FONT_HERSHEY_SIMPLEX

    for idx, f in enumerate(fibers, start=1):
        cnt = f["contour"]
        cx, cy = f["centroid"]

        if use_existing_index and ("index" in f) and (f["index"] is not None):
            fiber_id = int(f["index"])
        else:
            fiber_id = idx

        # expand contour
        temp = np.zeros((h, w), dtype=np.uint8)
        cv2.drawContours(temp, [cnt], -1, 255, 1)
        temp = cv2.dilate(temp, kernel, iterations=dilate_iters)
        new_cnts, _ = cv2.findContours(temp, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
        exp_cnt = new_cnts[0] if new_cnts else cnt

        # draw expanded contour + fiber ID
        cv2.drawContours(annotated, [exp_cnt], -1, (255, 255, 0), 2)
        cv2.putText(annotated,str(fiber_id),(int(cx) - 10, int(cy) - 10),font,0.9,(255, 255, 0),2)

        # label nuclei for this fiber
        nucleus_counter = 1
        for (nx, ny), r in zip(nuc_centers, nuc_radii):
            d = cv2.pointPolygonTest(exp_cnt, (float(nx), float(ny)), True)
            if d >= -dist_limit:
                cv2.circle(annotated, (nx, ny), int(r * 1.4), (255, 255, 0), 2)
                cv2.putText(annotated,str(nucleus_counter),(nx + 10, ny - 10),font,0.7,(255, 255, 0),2)
                nucleus_counter += 1
    return annotated
