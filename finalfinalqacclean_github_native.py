def extract_gt_fibers_from_quantified_image(path, show_mask=False, idx_mask=None, ocr_radius=60):
    img = cv2.imread(path)
    img_rgb = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

    # --- detect yellow outlines ---
    hsv = cv2.cvtColor(img_rgb, cv2.COLOR_RGB2HSV)
    lower_yellow = np.array([20, 40, 40])
    upper_yellow = np.array([50, 255, 255])

    yellow_mask = cv2.inRange(hsv, lower_yellow, upper_yellow)

    # thicken + close gaps
    k1 = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (5,5))
    yellow_mask = cv2.dilate(yellow_mask, k1, iterations=3)

    k2 = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (9,9))
    yellow_mask = cv2.morphologyEx(yellow_mask, cv2.MORPH_CLOSE, k2, iterations=2)

    cnts, _ = cv2.findContours(yellow_mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

    training_fibers = []

    for cnt in cnts:
        if cv2.contourArea(cnt) < 500:
            continue

        M = cv2.moments(cnt)
        if M["m00"] == 0:
            continue

        cx = M["m10"] / M["m00"]
        cy = M["m01"] / M["m00"]

        # --- OCR ---
        idx = ocr_single_digit(idx_mask, (cx, cy), radius=ocr_radius) if idx_mask is not None else None

        training_fibers.append({
            "contour": cnt,
            "centroid": (cx, cy),
            "area": cv2.contourArea(cnt),
            "index": idx
        })

    if show_mask:
        return training_fibers, yellow_mask, img_rgb
    return training_fibers

