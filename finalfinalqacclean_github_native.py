"""## Fiber Detection

### Creating a Fiber Mask
Enhance Membranes
- Increase the contrast in the green channel
- Convert to grayscale
- Boost local contrast with clahe  

Return grayscale, "enhanced" image

Get Fiber Mask
- Use enhance membranes function
- Otsu threshold on enhanced image
- Invert color
- Erode so fibers dont touch eachother
- Use distance transform to only threshold pixels closer to the center of the fiber  

Return the fiber mask image

#### Enhance Membranes and Example Output
"""

def enhance_membranes(img, alpha=0.5, beta=0.2):
    #given an image, it returns an "enhanced" image where:
    # noisier channels are subtracted
    # local contrast is increased with clahe
    b, g, r = cv2.split(img)

    #subtract b and r channels in various quantities
    enhanced = g.astype(np.float32) - alpha*b.astype(np.float32) - beta*r.astype(np.float32)
    enhanced = np.clip(enhanced, 0, 255).astype(np.uint8)

    #use clahe to boost local contrast in a 8x8 sized square
    clahe = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8, 8))
    enhanced = clahe.apply(enhanced)

    return enhanced

