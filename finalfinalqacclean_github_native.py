def get_fiber_mask(path):
    img = cv2.imread(path)

    #invert nanometer legend
    img = invert_nanometer_legend(img)

    # boost membrane contrast (green) so fibers stand out
    enhanced = enhance_membranes(img, alpha=0.3)

    # smooth noise a bit
    blur = cv2.GaussianBlur(enhanced, (5,5), 0)


    # threshold to get membrane vs interior
    _, mem = cv2.threshold(blur, 0, 255,
                           cv2.THRESH_BINARY + cv2.THRESH_OTSU)

    # flip so fiber interiors are white
    interior = 255 - mem

    # shrink interiors so fibers don’t touch each other
    small_k = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (3,3))
    interior = cv2.morphologyEx(interior, cv2.MORPH_ERODE, small_k, iterations=2)

    # distance map = how deep inside a fiber each pixel is
    dist = cv2.distanceTransform(interior, cv2.DIST_L2, 5)
    dist_norm = cv2.normalize(dist, None, 0, 255,
                              cv2.NORM_MINMAX).astype(np.uint8)

    # pick pixels “deep enough” → becomes our fiber mask
    _, fiber_mask = cv2.threshold(dist_norm, 25, 255,
                                  cv2.THRESH_BINARY)

    # clean up shape (fill holes)
    k_close = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (5,5))
    fiber_mask = cv2.morphologyEx(fiber_mask, cv2.MORPH_CLOSE, k_close, iterations=1)

    # remove tiny specks
    k_open = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (3,3))
    fiber_mask = cv2.morphologyEx(fiber_mask, cv2.MORPH_OPEN, k_open, iterations=1)

    # push mask outward closer to actual membrane
    k_dilate = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (5,5))
    fiber_mask = cv2.dilate(fiber_mask, k_dilate, iterations=2)

    return fiber_mask

