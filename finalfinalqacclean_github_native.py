def unzip_to(zip_path, out_dir):
    with zipfile.ZipFile(zip_path, "r") as z:
        z.extractall(out_dir)

def wipe_dir(d):
    if os.path.exists(d):
        shutil.rmtree(d)
    os.makedirs(d, exist_ok=True)

def collect_image_paths(root_dir, exts=(".jpg",".jpeg",".png",".tif",".tiff")):
    paths = []
    for r, _, fnames in os.walk(root_dir):
        for f in fnames:
            if f.lower().endswith(exts):
                paths.append(os.path.join(r, f))
    return paths

def build_basename_map(paths):
    """
    Returns a mapping of basename -> full path (first occurrence wins),
    and a list of dupes (if they exist)
    """
    mapping = {}
    dupes = []

    for p in paths:
        b = os.path.basename(p)
        if b in mapping:
            dupes.append(b)
        else:
            mapping[b] = p

    return mapping, dupes

def find_raw_for_quantified(qname, raw_files):
    """
    Match a quantified filename to its corresponding raw filename.

    Handles common prefixes produced by Drive/Finder:
      - "Quantified "
      - "Copy of Quantified "
      - "Copy of "
      - "Copy "

    Also tolerates leading junk like "-_", "_-", "-", "_", or spaces.
    """
    q = qname.lower().strip()

    # strip leading junk that sometimes appears in filenames
    q = q.lstrip(" _-")

    # strip common prefixes 
    prefixes = [
        "copy of quantified",
        "quantified",
        "copy of",
        "copy",
    ]
    for p in prefixes:
        if q.startswith(p):
            q = q[len(p):].strip()
            q = q.lstrip(" _-")  # in case something like "-_Quantified ..."
            break

    q_no_ext = os.path.splitext(q)[0]

    # build a lookup for exact basename matches (fast + reliable)
    raw_map = {os.path.splitext(r.lower().strip())[0]: r for r in raw_files}

    # exact match
    if q_no_ext in raw_map:
        return raw_map[q_no_ext]

    # fallback: substring match 
    for r in raw_files:
        r_no_ext = os.path.splitext(r.lower().strip())[0]
        if q_no_ext in r_no_ext:
            return r

    return None


