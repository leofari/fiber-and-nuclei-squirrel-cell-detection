"""### Check Fiber Distance and Get Fiber Candidates

#### Get contour distance (for fibers)
- First use the center of the fiber to rule out fibers which are far away using contours_too_close
- Then if two fibers' centers are sufficiently close, then use contour_min_distance to find the exact distance between the two fibers
- (contour_min_distance will also be useful for detecting nearby nuclei)
"""

def boxes_touch(b1, b2, margin=15):
    x1, y1, w1, h1 = b1
    x2, y2, w2, h2 = b2
    return (x1 < x2 + w2 + margin and
            x1 + w1 + margin > x2 and
            y1 < y2 + h2 + margin and
            y1 + h1 + margin > y2)

def contour_min_distance(c1, c2):

    #Return the minimum  distance between two contours c1 and c2.
    #c1 and c2 are arrays of shape (N, 1, 2) as returned by findContours.

    min_dist = float("inf")
    for p1 in c1:
        for p2 in c2:
            dx = p1[0][0] - p2[0][0]
            dy = p1[0][1] - p2[0][1]
            d2 = dx*dx + dy*dy
            if d2 < min_dist:
                min_dist = d2
    return np.sqrt(min_dist)


def contours_too_close(cnt, bbox, other_cnt, other_bbox, min_dist):
    #Return True if two contours are closer than min_dist pixels.
    #Uses bounding boxes to pre filter

    if not boxes_touch(bbox, other_bbox, margin=min_dist):
        return False

    # if boxes are near each other, check precise contour distance
    return contour_min_distance(cnt, other_cnt) < min_dist

def get_fiber_candidates(path):

    mask = get_fiber_mask(path)

    min_area = 600
    max_area = 1_000_000
    min_circularity = 0.1
    border_margin = 1
    min_contour_dist = 100   # non adjacent

    h, w = mask.shape

    contours, _ = cv2.findContours(
        mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE
    )

    fibers = []

    for cnt in contours:
        area = cv2.contourArea(cnt)
        if not (min_area < area < max_area):
            continue

        x, y, ww, hh = cv2.boundingRect(cnt)
        bbox = (x, y, ww, hh)

        # border rejection
        if x < border_margin or y < border_margin or \
           x+ww > w-border_margin or y+hh > h-border_margin:
            continue

        # perimeter
        peri = cv2.arcLength(cnt, True)
        if peri == 0:
            continue

        # circularity
        circularity = 4*np.pi*area/(peri**2)
        if circularity < min_circularity:
            continue

        # centroid
        M = cv2.moments(cnt)
        cx = M["m10"]/M["m00"]
        cy = M["m01"]/M["m00"]

        # adjacency filters using contour distance
        too_close = False
        for f in fibers:
            if contours_too_close(
                cnt, bbox,
                f["contour"], f["bbox"],
                min_dist=min_contour_dist
            ):
                too_close = True
                break

        if too_close:
            continue

        fibers.append({
            "contour": cnt,
            "centroid": (cx, cy),
            "area": area,
            "perimeter": peri,
            "circularity": circularity,
            "bbox": bbox
        })

    return fibers

