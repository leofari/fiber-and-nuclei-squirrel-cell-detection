"""### Wrap into one function"""

def get_matched_fibers(annotated_path, unannotated_path, show_mask=False):
    """
    Combines index-mask extraction, training fiber extraction,
    and matching into ONE function.
    """

    # 1) Get index mask
    idx_mask = get_index_mask(annotated_path, show_debug=False)

    # 2) Extract training fibers (returns FOUR values)
    training_fibers= extract_gt_fibers_from_quantified_image(
        annotated_path,
        show_mask=False,
        idx_mask=idx_mask
    )

    # 3) Match fibers
    matched_fibers = find_fiber_candidates_matched(
        unannotated_path,
        training_fibers
    )

    return matched_fibers

"""## Dataframe Logic"""

def parse_filename_metadata(image_path):
    """
    Parse SqID, State, Muscle, Slide, Section from a filename like:
        '240305_MIDHIB_GASTRO_A1_Sect2_0001 2.jpg'

    Assumes pattern:
        SqID_State_Muscle_Slide_Section_...
    """
    fname = os.path.basename(image_path)

    #we made a copy of the images to make the sharing permissions public for !gdown
    #But this line is harmless if the image doesn't contain "Copy of " anyway
    fname = fname.replace("Copy of ", '')
    root, _ = os.path.splitext(fname)

    parts = root.split("_")

    SqID   = parts[0]
    State  = parts[1]
    Muscle = parts[2].upper()
    Slide  = parts[3]
    Section = parts[4]

    return SqID, State, Muscle, Slide, Section

def fiber_metrics_dataframe(path, fibers, use_existing_index=False):
    """
    For a single image, return a DataFrame with:
      SqID, State, Muscle, Slide, Section, Fiber Number, CSA, MyoN
    """
    SqID, State, Muscle, Slide, Section = parse_filename_metadata(path)
    metrics = compute_fiber_metrics(path, fibers=fibers, use_existing_index=use_existing_index)

    rows = []
    for m in metrics:
        rows.append({
            "SqID": SqID,
            "State": State,
            "Muscle": Muscle,
            "Slide": Slide,
            "Section": Section,
            "Fiber Number": m["fiber_id"],
            "CSA": m["CSA"],
            "MyoN": m["nuclei_count"],
        })

    df = pd.DataFrame(rows).sort_values("Fiber Number").reset_index(drop=True)
    return df

