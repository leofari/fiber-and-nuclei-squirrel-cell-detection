def evaluate_fiber_pipeline(final_df, squirrel_df, verbose=True):
    """
    Compare predicted fiber metrics (final_df) against ground truth (squirrel_df).
    """

    import numpy as np
    import pandas as pd
    from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

    pred = final_df.copy()
    gt = squirrel_df.copy()

    # Normalize merge keys
    def normalize_section(x):
        if pd.isna(x):
            return None
        return "".join(c for c in str(x) if c.isdigit())

    for df in (pred, gt):
        df["SqID"] = df["SqID"].astype(str)
        df["Muscle"] = df["Muscle"].astype(str)
        df["Section"] = df["Section"].apply(normalize_section)
        df["Fiber Number"] = df["Fiber Number"].astype(int)

    pred = pred.rename(columns={"CSA": "CSA_pred", "MyoN": "MyoN_pred"})
    gt = gt.rename(columns={"CSA": "CSA_gt", "MyoN": "MyoN_gt"})

    results = {}

    # Fiber-level evaluation
    fiber_eval = pd.merge(
        pred,
        gt,
        on=["SqID", "Muscle", "Section", "Fiber Number"],
        how="inner"
    )

    results["coverage"] = {
        "pred_fibers": len(pred),
        "gt_fibers": len(gt),
        "matched_fibers": len(fiber_eval),
        "fiber_match_rate": len(fiber_eval) / max(len(gt), 1)
    }

    if len(fiber_eval) > 0:
        results["fiber_metrics"] = {
            "CSA_MAE": mean_absolute_error(fiber_eval["CSA_gt"], fiber_eval["CSA_pred"]),
            "CSA_RMSE": np.sqrt(mean_squared_error(
                fiber_eval["CSA_gt"], fiber_eval["CSA_pred"]
            )),
            "CSA_R2": r2_score(fiber_eval["CSA_gt"], fiber_eval["CSA_pred"]),
            "MyoN_MAE": mean_absolute_error(
                fiber_eval["MyoN_gt"], fiber_eval["MyoN_pred"]
            ),
            "MyoN_RMSE": np.sqrt(mean_squared_error(
                fiber_eval["MyoN_gt"], fiber_eval["MyoN_pred"]
            )),
            "MyoN_Exact_Accuracy": np.mean(
                fiber_eval["MyoN_gt"] == fiber_eval["MyoN_pred"]
            )
        }
    else:
        results["fiber_metrics"] = None

    # Section-level evaluation
    pred_sec = (
        pred
        .groupby(["SqID", "Muscle", "Section"])
        .agg(
            CSA_pred_mean=("CSA_pred", "mean"),
            CSA_pred_sum=("CSA_pred", "sum"),
            MyoN_pred_sum=("MyoN_pred", "sum"),
            n_fibers_pred=("Fiber Number", "count")
        )
        .reset_index()
    )

    gt_sec = (
        gt
        .groupby(["SqID", "Muscle", "Section"])
        .agg(
            CSA_gt_mean=("CSA_gt", "mean"),
            CSA_gt_sum=("CSA_gt", "sum"),
            MyoN_gt_sum=("MyoN_gt", "sum"),
            n_fibers_gt=("Fiber Number", "count")
        )
        .reset_index()
    )

    sec_eval = pd.merge(
        pred_sec,
        gt_sec,
        on=["SqID", "Muscle", "Section"],
        how="inner"
    )

    if len(sec_eval) > 0:
        results["section_metrics"] = {
            "CSA_mean_MAE": mean_absolute_error(
                sec_eval["CSA_gt_mean"], sec_eval["CSA_pred_mean"]
            ),
            "CSA_sum_MAE": mean_absolute_error(
                sec_eval["CSA_gt_sum"], sec_eval["CSA_pred_sum"]
            ),
            "MyoN_sum_MAE": mean_absolute_error(
                sec_eval["MyoN_gt_sum"], sec_eval["MyoN_pred_sum"]
            ),
            "Fiber_count_MAE": mean_absolute_error(
                sec_eval["n_fibers_gt"], sec_eval["n_fibers_pred"]
            ),
            "n_sections_evaluated": len(sec_eval)
        }
    else:
        results["section_metrics"] = None

    # Print summary
    if verbose:
        print("\n=== Coverage ===")
        print(f"pred_fibers        : {results['coverage']['pred_fibers']}")
        print(f"gt_fibers          : {results['coverage']['gt_fibers']}")
        print(f"matched_fibers     : {results['coverage']['matched_fibers']}")
        print(f"fiber_match_rate   : {results['coverage']['fiber_match_rate']:.4f}")

        print("\n=== Fiber-level metrics ===")
        fm = results["fiber_metrics"]
        if fm is None:
            print("No matched fibers")
        else:
            print(f"CSA_MAE            : {float(fm['CSA_MAE']):.2f}")
            print(f"CSA_RMSE           : {float(fm['CSA_RMSE']):.2f}")
            print(f"CSA_R2             : {float(fm['CSA_R2']):.3f}")
            print(f"MyoN_MAE           : {float(fm['MyoN_MAE']):.2f}")
            print(f"MyoN_RMSE          : {float(fm['MyoN_RMSE']):.2f}")
            print(f"MyoN_Exact_Acc     : {float(fm['MyoN_Exact_Accuracy']):.3f}")

        print("\n=== Section-level metrics ===")
        sm = results["section_metrics"]
        if sm is None:
            print("No matched sections")
        else:
            print(f"CSA_mean_MAE       : {float(sm['CSA_mean_MAE']):.2f}")
            print(f"CSA_sum_MAE        : {float(sm['CSA_sum_MAE']):.2f}")
            print(f"MyoN_sum_MAE       : {float(sm['MyoN_sum_MAE']):.2f}")
            print(f"Fiber_count_MAE    : {float(sm['Fiber_count_MAE']):.2f}")
            print(f"n_sections_eval    : {sm['n_sections_evaluated']}")

    return results

