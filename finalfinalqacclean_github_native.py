"""### Building First Nuclei Mask
Build first mask by:
- Seperating channels
- Subtracting blue from green to isolate "blueness"
- Using clahe to improve local contrast
- Using Otsu to threshold based on image histogram  

Returns a cv2 image of the first mask
"""

def build_first_mask(impath):
    #Given an image path, return a binary mask of nuclei.
    img = cv2.imread(impath) # import image
    b, g, r = cv2.split(img) # isolate three channels

    blueness = cv2.subtract(b, g) # subtract green from blue to isolate nuclei

    # Use clahe to improve local contrast in  images
    clahe = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(6, 6))
    blueness_eq = clahe.apply(blueness)


    # Use otsu to threshold the
    otsu_T, _ = cv2.threshold(
      blueness_eq, 0, 255,
      cv2.THRESH_BINARY + cv2.THRESH_OTSU
    )
    # Then I found more success adjusting otsu threshold by a bit
    T = max(1, int(otsu_T - 5))
    _, nuc_mask = cv2.threshold(blueness_eq, T, 255, cv2.THRESH_BINARY)
    return nuc_mask

