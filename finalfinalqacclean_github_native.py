def get_index_mask(path, show_debug=False):
    img = cv2.imread(path)
    img_rgb = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

    # Detect pixels where R,G,B are almost equal (gray-ish text)
    R = img_rgb[:,:,0].astype(np.int16)
    G = img_rgb[:,:,1].astype(np.int16)
    B = img_rgb[:,:,2].astype(np.int16)

    t = 12  # threshold for RGB similarity

    eq_mask = (
        (np.abs(R - G) < t) &
        (np.abs(G - B) < t) &
        (np.abs(R - B) < t)
    )

    # Preserve original brightness of the pixel
    gray = cv2.cvtColor(img_rgb, cv2.COLOR_RGB2GRAY)
    idx_mask = np.zeros_like(gray)
    idx_mask[eq_mask] = gray[eq_mask]

    # Debug display (ONLY the first image)
    if show_debug:
        plt.figure(figsize=(20,20))
        plt.imshow(idx_mask, cmap="gray")
        plt.title("Gray-ish pixels (brightness preserved)")
        plt.axis("off")
        plt.show()

    return idx_mask

